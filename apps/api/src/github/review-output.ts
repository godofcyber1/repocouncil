import type { ReviewFinding } from "@repocouncil/shared";

export type CheckAnnotationLevel = "notice" | "warning" | "failure";

export type CheckAnnotation = {
  path: string;
  start_line: number;
  end_line: number;
  annotation_level: CheckAnnotationLevel;
  title: string;
  message: string;
  raw_details?: string;
};

export type CheckConclusion = "success" | "neutral" | "failure";

export type CheckRunOutput = {
  title: string;
  summary: string;
  text: string;
  annotations: CheckAnnotation[];
  conclusion: CheckConclusion;
};

export type ReviewOutputOptions = {
  maxAnnotations?: number;
  dashboardUrl?: string;
  reviewerContributions?: ReviewerContribution[];
};

export type ReviewerContribution = {
  label: string;
  summary: string;
};

const DEFAULT_MAX_ANNOTATIONS = 50;
const SEVERITY_RANK: Record<ReviewFinding["severity"], number> = {
  critical: 5,
  high: 4,
  medium: 3,
  low: 2,
  info: 1
};

export function buildCheckRunOutput(
  findings: ReviewFinding[],
  options: ReviewOutputOptions = {}
): CheckRunOutput {
  const sortedFindings = sortFindings(findings);
  const maxAnnotations = options.maxAnnotations ?? DEFAULT_MAX_ANNOTATIONS;
  const annotations = sortedFindings
    .filter(hasLineLocation)
    .slice(0, maxAnnotations)
    .map(toCheckAnnotation);

  return {
    title: "RepoCouncil review",
    summary: buildCheckSummary(sortedFindings, annotations.length),
    text: buildSummaryMarkdown(sortedFindings, options),
    annotations,
    conclusion: determineConclusion(sortedFindings)
  };
}

export function buildPullRequestSummary(
  findings: ReviewFinding[],
  options: ReviewOutputOptions = {}
): string {
  return buildSummaryMarkdown(sortFindings(findings), options);
}

function sortFindings(findings: ReviewFinding[]): ReviewFinding[] {
  return [...findings].sort((left, right) => {
    const severityDelta = SEVERITY_RANK[right.severity] - SEVERITY_RANK[left.severity];

    if (severityDelta !== 0) {
      return severityDelta;
    }

    return right.confidence - left.confidence;
  });
}

function toCheckAnnotation(finding: ReviewFinding): CheckAnnotation {
  return {
    path: finding.file,
    start_line: finding.startLine!,
    end_line: finding.endLine ?? finding.startLine!,
    annotation_level: toAnnotationLevel(finding.severity),
    title: truncate(finding.title, 255),
    message: truncate(buildAnnotationMessage(finding), 65535),
    raw_details: buildRawDetails(finding)
  };
}

function hasLineLocation(finding: ReviewFinding): finding is ReviewFinding & {
  startLine: number;
} {
  return finding.startLine !== undefined;
}

function toAnnotationLevel(severity: ReviewFinding["severity"]): CheckAnnotationLevel {
  if (severity === "critical" || severity === "high") {
    return "failure";
  }

  if (severity === "medium") {
    return "warning";
  }

  return "notice";
}

function determineConclusion(findings: ReviewFinding[]): CheckConclusion {
  const hasSevereFinding = findings.some(
    (finding) =>
      (finding.severity === "critical" || finding.severity === "high") &&
      finding.confidence >= 0.75
  );

  if (hasSevereFinding) {
    return "failure";
  }

  return findings.length === 0 ? "success" : "neutral";
}

function buildCheckSummary(findings: ReviewFinding[], annotationCount: number): string {
  if (findings.length === 0) {
    return "RepoCouncil found no issues in this review run.";
  }

  return `RepoCouncil found ${findings.length} finding(s). ${annotationCount} were mapped to inline annotations.`;
}

function buildSummaryMarkdown(
  findings: ReviewFinding[],
  options: ReviewOutputOptions
): string {
  const lines = ["## RepoCouncil Review", ""];

  if (findings.length === 0) {
    lines.push("No findings were reported for this review run.");
  } else {
    lines.push(`Found **${findings.length}** final finding(s).`);
    lines.push("");
    lines.push("| Severity | Confidence | Location | Finding |");
    lines.push("|---|---:|---|---|");

    for (const finding of findings.slice(0, 10)) {
      lines.push(
        `| ${finding.severity} | ${Math.round(finding.confidence * 100)}% | ${formatLocation(
          finding
        )} | ${escapeMarkdownTableCell(finding.title)} |`
      );
    }

    if (findings.length > 10) {
      lines.push("");
      lines.push(`Showing the top 10 findings out of ${findings.length}.`);
    }
  }

  if (options.reviewerContributions && options.reviewerContributions.length > 0) {
    lines.push("");
    lines.push("### Reviewer contribution");
    lines.push("");

    for (const contribution of options.reviewerContributions) {
      lines.push(`- ${contribution.label}: ${contribution.summary}`);
    }
  }

  if (options.dashboardUrl) {
    lines.push("");
    lines.push(`[Open RepoCouncil dashboard](${options.dashboardUrl})`);
  }

  lines.push("");
  lines.push("_Generated by RepoCouncil. Human review is still required._");

  return lines.join("\n");
}

function buildAnnotationMessage(finding: ReviewFinding): string {
  const sections = [finding.body];

  if (finding.suggestedPatch) {
    sections.push(`Suggested patch:\n${finding.suggestedPatch}`);
  }

  if (finding.suggestedTests) {
    sections.push(`Suggested tests:\n${finding.suggestedTests}`);
  }

  return sections.join("\n\n");
}

function buildRawDetails(finding: ReviewFinding): string {
  const sections = [
    `Category: ${finding.category}`,
    `Confidence: ${Math.round(finding.confidence * 100)}%`
  ];

  if (finding.evidence.length > 0) {
    sections.push(`Evidence:\n${finding.evidence.map((item) => `- ${item}`).join("\n")}`);
  }

  if (finding.suggestedTests) {
    sections.push(`Suggested tests:\n${finding.suggestedTests}`);
  }

  if (finding.suggestedPatch) {
    sections.push(`Suggested patch:\n${finding.suggestedPatch}`);
  }

  return sections.join("\n\n");
}

function formatLocation(finding: ReviewFinding): string {
  if (!finding.startLine) {
    return finding.file;
  }

  if (finding.endLine && finding.endLine !== finding.startLine) {
    return `${finding.file}:${finding.startLine}-${finding.endLine}`;
  }

  return `${finding.file}:${finding.startLine}`;
}

function escapeMarkdownTableCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function truncate(value: string, maxLength: number): string {
  return value.length <= maxLength ? value : `${value.slice(0, maxLength - 3)}...`;
}
